const assert=require('node:assert/strict');
const fs=require('node:fs');
const vm=require('node:vm');
const sandbox={window:{},Math};
vm.runInNewContext(fs.readFileSync('src/config.js','utf8'),sandbox);
vm.runInNewContext(fs.readFileSync('src/pesol.js','utf8'),sandbox);
const cfg=sandbox.window.CONFIG.pesol;
const limits=sandbox.window.CONFIG.limites;
const AI=sandbox.window.Pesol;
const hero={x:100,y:365};
const fresh=()=>AI.crear(cfg);
const e=fresh();
assert.equal(e.hp,cfg.vida);
assert.equal(e.state,'IDLE');
assert.equal(AI.pose(e).fila,0);
AI.avanzar(e,hero,.02,cfg,limits);
assert.equal(e.state,'CHASE','detecta al jugador');
const before=e.x;AI.avanzar(e,hero,.05,cfg,limits);
assert(e.x<before,'persigue al jugador');
assert.equal(e.facing,-1);
e.x=158;e.y=365;AI.cambiar(e,'CHASE');
AI.avanzar(e,hero,.03,cfg,limits);
assert.equal(e.state,'PRE_ATTACK','anuncia el golpe antes de atacar');
assert.equal(AI.pose(e).fila,2);
for(let i=0;i<18;i++)AI.avanzar(e,hero,.02,cfg,limits);
assert.equal(e.state,'ATTACK','preparación completa');
let hits=0;
for(let i=0;i<18;i++){
 if(AI.avanzar(e,hero,.02,cfg,limits).golpeJugador)hits++;
}
assert.equal(hits,1,'solo hay un impacto por cabotada');
assert.equal(e.state,'RECOVER','retraso antes de otro ataque');
assert.equal(AI.pose(e).fila,0);
for(let i=0;i<29;i++)AI.avanzar(e,hero,.02,cfg,limits);
assert(['CHASE','PRE_ATTACK'].includes(e.state),'tras recuperarse puede empezar un nuevo ataque si el jugador sigue cerca');
const wounded=fresh();
assert(AI.recibirGolpe(wounded,1,1,16,limits,cfg));
assert.equal(wounded.hp,cfg.vida-1);assert.equal(wounded.state,'HURT');
assert.equal(AI.pose(wounded).fila,3);
assert.equal(AI.avanzar(wounded,hero,.1,cfg,limits).golpeJugador,false);
assert(AI.recibirGolpe(wounded,cfg.vida,1,24,limits,cfg));
assert.equal(wounded.hp,0);assert.equal(wounded.state,'KO');
for(let i=0;i<35;i++)AI.avanzar(wounded,hero,.02,cfg,limits);
assert.equal(AI.pose(wounded).fila,4);
assert.equal(AI.pose(wounded).frame,2,'último fotograma de caída persistente');
assert.equal(AI.recibirGolpe(wounded,1,1,20,limits,cfg),false,'no revivir al KO');
assert.equal(wounded.hp,0);
console.log('Pèsol: detección, persecución, aviso, golpe único, recuperación, daño y KO.');
