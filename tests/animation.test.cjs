const assert=require('node:assert/strict');
const fs=require('node:fs');
const vm=require('node:vm');
const sandbox={window:{}};
vm.runInNewContext(fs.readFileSync('src/animation.js','utf8'),sandbox);
const {frame,frameUnico}=sandbox.window.Animacion;
assert.equal(frame(0,6,4),0,'empieza en fotograma cero');
assert.equal(frame(0.18,6,4),1,'avanza según el reloj');
assert.equal(frame(0.50,6,4),3,'cuarto fotograma');
assert.equal(frame(0.67,6,4),0,'repite en bucle');
assert.equal(frame(-1,6,4),0,'tiempo negativo seguro');
assert.equal(frame(1,0,4),0,'fps cero seguro');
assert.equal(frameUnico(0,0.34,4),0,'primer fotograma del ataque');
assert.equal(frameUnico(0.13,0.34,4),1,'avance del golpe');
assert.equal(frameUnico(0.17,0.34,4),2,'fase avanzada del golpe');
assert.equal(frameUnico(0.34,0.34,4),3,'fotograma final');
assert.equal(frameUnico(10,0.34,4),3,'no se repite el golpe');
assert.equal(frameUnico(-1,0.34,4),0,'tiempo negativo seguro');
assert.equal(frameUnico(1,0,4),0,'duracion cero segura');
console.log('13 comprobaciones de animación superadas.');
