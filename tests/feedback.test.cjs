const assert=require('node:assert/strict');
const fs=require('node:fs'),vm=require('node:vm');
const env={window:{}};
vm.runInNewContext(fs.readFileSync('src/feedback.js','utf8'),env);
vm.runInNewContext(fs.readFileSync('src/config.js','utf8'),env);
const F=env.window.Feedback,C=env.window.CONFIG;
const r=F.repartirDelta(.02,.075);
assert(Math.abs(r.accion)<1e-8,'durante hit-stop no avanza el frame');
assert(Math.abs(r.restante-.055)<1e-8);
const s=F.repartirDelta(.05,.01);
assert(Math.abs(s.accion-.04)<1e-8,'fracción restante recupera simulación');
assert.equal(s.restante,0);
assert.equal(F.intensidad(0,.18),0);
assert.equal(F.intensidad(.18,.18),1);
assert(F.intensidad(.09,.18)<1);
assert.equal(F.sacudida(0,.18,6).x,0);
assert(Math.abs(F.sacudida(.09,.18,6).x)<=3.01);
assert.equal(C.ataque.movimientos[3].dano,2);
assert.equal(C.ataque.movimientos[3].alcance,128);
assert.equal(C.ataque.movimientos[3].impacto,.20);
const game=fs.readFileSync('src/game.js','utf8'), html=fs.readFileSync('index.html','utf8');
assert(game.includes('game.hitStop=config.feedbackRemate.pausa'));
assert(game.includes('p.stateTime+=hold.accion;'));
assert(game.includes('drawImpactBurst();'));
assert(html.includes('id="strong-impact"'));
console.log('Feedback remate 03N: hit-stop, sacudida, destello y mecánica intacta.');
